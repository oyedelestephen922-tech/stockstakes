/**
 * Writes the files the website reads:
 *   lib/web3/deployment.ts  contract addresses per chain (from deployments/*.json)
 *   lib/web3/abis.ts        ABIs of StakesRounds and StakesOracle (from artifacts/)
 *
 * Run automatically by deploy.ts; standalone: `npm run export:site`.
 * Local simulations (deployments/local-*.json) are only included for chain
 * 31337 and only with EXPORT_LOCAL=1, so a rehearsal never leaks into the site.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const siteWeb3 = new URL("../lib/web3/", root);

interface Saved {
  chainId: number;
  StakesOracle: { address?: string; block?: number };
  StakesRounds: { address?: string; block?: number };
}

export function exportSiteFiles(): string[] {
  const dir = new URL("deployments/", root);
  const includeLocal = process.env.EXPORT_LOCAL === "1";
  const entries: string[] = [];
  if (existsSync(dir)) {
    for (const file of readdirSync(dir).sort()) {
      if (!file.endsWith(".json")) continue;
      if (file.startsWith("local-") && !(includeLocal && file === "local-31337.json")) continue;
      const d = JSON.parse(readFileSync(new URL(file, dir), "utf8")) as Saved;
      if (!d.StakesOracle.address || !d.StakesRounds.address) continue;
      entries.push(
        `  ${d.chainId}: {\n` +
          `    chainId: ${d.chainId},\n` +
          `    stakesRounds: "${d.StakesRounds.address}",\n` +
          `    stakesOracle: "${d.StakesOracle.address}",\n` +
          `    deployBlock: ${d.StakesRounds.block ?? 0},\n` +
          `  },\n`,
      );
    }
  }

  const deployment =
    `// Generated by contracts/scripts/export-site.ts — do not edit by hand.\n` +
    `// Re-generate with: cd contracts && npm run export:site\n\n` +
    `export interface Deployment {\n` +
    `  chainId: number;\n` +
    `  stakesRounds: \`0x\${string}\`;\n` +
    `  stakesOracle: \`0x\${string}\`;\n` +
    `  /** Block StakesRounds was deployed in — the earliest block worth scanning for events. */\n` +
    `  deployBlock: number;\n` +
    `}\n\n` +
    `export const deployments: Record<number, Deployment> = {\n${entries.join("")}};\n`;

  const abi = (name: string) =>
    JSON.stringify(
      JSON.parse(readFileSync(new URL(`artifacts/contracts/${name}.sol/${name}.json`, root), "utf8")).abi,
      null,
      2,
    );
  const abis =
    `// Generated by contracts/scripts/export-site.ts — do not edit by hand.\n\n` +
    `export const stakesRoundsAbi = ${abi("StakesRounds")} as const;\n\n` +
    `export const stakesOracleAbi = ${abi("StakesOracle")} as const;\n`;

  const out = [new URL("deployment.ts", siteWeb3), new URL("abis.ts", siteWeb3)];
  writeFileSync(out[0], deployment);
  writeFileSync(out[1], abis);
  return out.map((u) => fileURLToPath(u).replace(fileURLToPath(new URL("../", root)), ""));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log("Wrote", exportSiteFiles().join(", "));
}
